import { ERROR_CODES, type ErrorCode } from '@/lib/errors';

const FAILURE_MAP: Record<string, ErrorCode> = {
  UNKNOWN_CARD: 'UNKNOWN_CARD',
  CARD_NOT_ACTIVE: 'CARD_NOT_ACTIVE',
  CARD_EXPIRED: 'CARD_EXPIRED',
  INVALID_CREDENTIAL: 'INVALID_CREDENTIAL',
  WALLET_FROZEN: 'WALLET_FROZEN',
  INSUFFICIENT_FUNDS: 'INSUFFICIENT_FUNDS',
  LIMIT_EXCEEDED: 'LIMIT_EXCEEDED',
  RESTRICTED_PRODUCT: 'RESTRICTED_PRODUCT',
  PRODUCT_UNAVAILABLE: 'PRODUCT_UNAVAILABLE',
  INSUFFICIENT_STOCK: 'INSUFFICIENT_STOCK',
  SHIFT_REQUIRED: 'SHIFT_REQUIRED',
  IDEMPOTENCY_CONFLICT: 'IDEMPOTENCY_CONFLICT',
  CHECK_FAILED: 'INSUFFICIENT_FUNDS',
  SYSTEM_ERROR: 'SYSTEM_ERROR',
};

export function messageForFailureCode(code: string): string {
  const key = FAILURE_MAP[code] ?? 'SYSTEM_ERROR';
  return ERROR_CODES[key];
}
